// 贴纸 —— 贴在角色脸上的模切贴纸。
//
// 原版怎么做的：作者在 Blender 里把十几张贴纸平面手工贴到脸上，跟模型一起导出成 glb。
// 你机器上没有 Blender，模型也是「图片→3D」的静态网格，所以这里改成
// **运行时把贴纸"打"到模型表面上**：
//
//   每张贴纸只描述「往脸上哪个位置打一枪」（tx / ty），代码从正前方沿 -Z 发一条射线，
//   打到模型表面后就地生成一个平面，**朝向贴着该点的表面法线**，再沿法线往外推 offset。
//   → 贴纸像真贴纸一样伏在皮肤曲面上，不是浮在空中；头一转，贴纸跟着头一起转。
//
// 坐标（**世界单位**，与人物归一化身高一致）：
//   y：0 = 脚底，2.6 = 头顶
//   x：正 = 画面右，负 = 画面左
//
// ── 密度为什么是 9 张，而不是 16 张 ──────────────────────────────────
// 第一版铺了 16 张，结果是脸上糊成一坨彩色圆点。算一下就明白：
// 可贴皮肤区只有 0.24 × 0.24（脸本来就小，两颊还被头发框住），
// 16 张平均 0.062 的贴纸 → 覆盖 16×0.062²/(0.24×0.24) ≈ **107%**，必然互相压边。
// 对照原版实拍（about.senbuzy.com）：人家的贴纸**大而疏、留白明显**，
// 每张约占脸宽 1/4，彼此不重叠 —— 所以关键是「少而准」，不是「多而密」。
//
// 现在这 8 个位置是按**最小边缘空隙 ≥ 0.012** 挑的（相邻两张中心距 ≥ 0.07），
// size 0.058~0.072（占脸宽 24%~30%），与原版比例一致；并且整片避开双眼。
// 位置全部落在 `_tools/autoplace.cjs` 验过的「皮肤区」格点上，最后一张故意压到
// 鬓角头发上（原版脸上也有贴纸吃进头发）。
//
// ⚠️ 禁区：眼睛。`_tools/facmap.cjs` 把命中点的贴图颜色分了类（皮肤亮 / 头发眼窝深），
//   量出来右眼在 x∈[0.085,0.16]、左眼在 x∈[−0.12,−0.04]，两眼 y∈[2.19,2.26]。
//   贴纸压到瞳孔上非常难看（第一版「宠物」就糊在左眼上），所以 D 的底边卡在 2.265、
//   B/C 的底边卡在 2.28 以上，眼睛整片留白。想自己挪：node _tools/facmap.cjs 会重出这张图。
//
// 重扫位置：node _tools/autoplace.cjs 9
// 核对落点：node _tools/stickdbg.cjs   （打印瞄准点 vs 真实命中点 + 表面法线）
// 照着挪：node _tools/overlay.cjs，会把世界坐标网格叠在画面上
//
// 想换成自己的内容：覆盖 public/stickers/<file>.webp，本文件不用改。

export type StickerDef = {
  file: string // public/stickers/<file>.webp
  label: string // 仅注释用
  tx: number // 射线瞄准的世界 X
  ty: number // 射线瞄准的世界 Y
  size: number // 贴纸长边（世界单位；脸宽约 0.24，即 size 0.06 ≈ 脸宽 25%）
  tilt: number // 贴到脸上后的面内旋转（度），做出手工贴歪的感觉
  offset: number // 沿表面法线往外推的距离（防 z-fighting，也防平面在曲面上"陷边"）
}

// 统一 offset：脸曲率半径约 0.12，0.06 宽的平面贴上去边缘会陷进曲面 ~0.004，
// 推 0.007 刚好让四边都浮在皮肤之上，又看不出"浮着"。
