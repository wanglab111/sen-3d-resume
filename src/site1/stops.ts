/** 第 from 站 → 第 to 站要放多少毫秒（按两站之间的帧数折算） */
export const stepDuration = (from: number, to: number) => {
  const gap = Math.abs(BEATS[Math.max(0, to)].frame - BEATS[Math.max(0, from)].frame)
  return Math.min(MAX_STEP_MS, Math.max(MIN_STEP_MS, Math.round(gap * MS_PER_FRAME)))
}

/* ── 帧图有**两套**（生成脚本 `_tools/site1_frames_mobile.py`）──────────
     桌面 `site1/frames/f###.jpg`  ：1600×900，189 张 ≈ 11MB
     手机 `site1/frames-m/f###.webp`：1080×608，189 张 ≈ 2.4MB
   两套**互斥加载**（这里选哪套，就只请求哪套）。手机上首次打开少下 8.6MB ——
   这是"手机上要转很久圈"的唯一根因，画面本身没有任何改动。

   选哪套**按真实像素需求算，不按设备名**：
   竖屏的 fit() 是「宽铺满 + 1.35 轻裁」，最终画布宽 = 视口宽 × 1.35 × min(DPR,2)
   （见 Site1.tsx）。这个值 ≤ 1200 用手机套就完全够（390×2×1.35 ≈ 1053）。
   再加一条「最短边 ≤ 500」兜手机横屏（844×390 横过来时上式会算出 2279，
   只是横着拿而已，不该因此退回 11MB）。

   ⚠️ 只在**首帧之前**定一次：加载到一半换套 = 帧号错位 + 白下两遍。 */
const FRAME_DIR = (() => {
  if (typeof window === 'undefined') return 'frames'
  const dpr = Math.min(window.devicePixelRatio || 1, 2)
  const need = window.innerWidth * 1.35 * dpr
  const phoneish = Math.min(window.innerWidth, window.innerHeight) <= 500
  return need <= 1200 || phoneish ? 'frames-m' : 'frames'
})()

/** 给验收脚本读的：这一趟实际吃的是哪套帧（`__site1.frameSet`） */
export const FRAME_SET = FRAME_DIR === 'frames-m' ? 'mobile' : 'desktop'

export const frameSrc = (i: number) => {
  const n = String(i).padStart(3, '0')
  return FRAME_DIR === 'frames-m'
    ? `${import.meta.env.BASE_URL}site1/frames-m/f${n}.webp`
    : `${import.meta.env.BASE_URL}site1/frames/f${n}.jpg`
}
